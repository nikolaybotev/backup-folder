#!/usr/bin/env bash
set -euo pipefail

if [[ "$(uname -s)" != "Darwin" ]]; then
  echo "scripts/build.sh requires macOS" >&2
  exit 1
fi

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

mkdir -p Sources/BuildStamp

if [[ -n "${VERSION:-}" ]]; then
  ver="$VERSION"
else
  if ! ver="$(git describe --tags --dirty 2>/dev/null)"; then
    echo "scripts/build.sh: cannot determine version (set VERSION or tag the repo)" >&2
    exit 1
  fi
fi

if ! sha="$(git rev-parse HEAD 2>/dev/null)"; then
  echo "scripts/build.sh: git rev-parse HEAD failed" >&2
  exit 1
fi

ts="$(date -u +%Y-%m-%dT%H:%MZ)"

cat >Sources/BuildStamp/BuildStamp.swift <<SWIFT
// Generated by scripts/build.sh — do not commit
enum BuildStampInfo {
    static let version = "${ver}"
    static let commitSHA = "${sha}"
    static let buildTimestamp = "${ts}"
}
SWIFT

export MACOSX_DEPLOYMENT_TARGET=12.0
# CodeQL's Swift tracer runs as osx64 and otherwise selects an x86_64 link
# destination while Package.swift compiles arm64; --arch arm64 keeps link and
# objects on the same architecture (see GitHub CodeQL Swift build guidance).
if [[ -n "${CODEQL_RUNNER:-}" ]]; then
  swift build -c release --arch arm64
else
  swift build -c release
fi

cp .build/release/backup-folder "$ROOT/backup-folder"

watcher_dest="$ROOT/drop-box-watcher"
if [[ -d "$watcher_dest" ]]; then
  # Source tree lives at drop-box-watcher/; on macOS the root name is the directory.
  watcher_dest="$ROOT/drop-box-watcher/drop-box-watcher"
fi
cp .build/release/drop-box-watcher "$watcher_dest"

sign_one() {
  local bin="$1"
  if [[ -n "${SIGN_IDENTITY:-}" ]]; then
    codesign --sign "$SIGN_IDENTITY" --force --options runtime "$bin"
  else
    codesign --sign - --force "$bin"
  fi
}

sign_one "$ROOT/backup-folder"
sign_one "$watcher_dest"
